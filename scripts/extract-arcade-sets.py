#!/usr/bin/env python3
"""Extract TatoEmu/FBNeo ROM name, size, and CRC tables from tatoemu.wasm.

The browser rename step uses this table. CRCs are the public catalog values
stored in the emulator, not ROM bytes.
"""
import struct
from pathlib import Path

WASM = Path('public/emulator/tatoemu.wasm')
OUT = Path('src/arcade-romsets.ts')


def read_leb(buf, i):
    size = 0
    shift = 0
    while True:
        b = buf[i]
        i += 1
        size |= (b & 0x7F) << shift
        if b < 128:
            break
        shift += 7
    return size, i


def load_memory(blob: bytes) -> bytearray:
    pos = 8
    body = None
    while pos < len(blob):
        sid = blob[pos]
        pos += 1
        size, pos = read_leb(blob, pos)
        if sid == 11:
            body = blob[pos:pos + size]
            break
        pos += size
    if body is None:
        raise SystemExit('wasm data section missing')
    count, i = read_leb(body, 0)
    segs = []
    for _ in range(count):
        i += 1  # flags
        if body[i] != 0x41:
            raise SystemExit('unexpected data offset')
        i += 1
        val = 0
        shift = 0
        while True:
            b = body[i]
            i += 1
            val |= (b & 0x7F) << shift
            shift += 7
            if b < 128:
                if shift < 32 and (b & 0x40):
                    val |= (~0 << shift)
                break
        val &= 0xFFFFFFFF
        if body[i] != 0x0B:
            raise SystemExit('expected end')
        i += 1
        dlen, i = read_leb(body, i)
        segs.append((val, body[i:i + dlen]))
        i += dlen
    hi = max(base + len(chunk) for base, chunk in segs)
    mem = bytearray(hi + 64)
    for base, chunk in segs:
        mem[base:base + len(chunk)] = chunk
    return mem


def cstr(mem, addr, limit=80):
    if not (0 < addr < len(mem) - 1):
        return None
    end = mem.find(b'\x00', addr, addr + limit)
    if end < 0:
        return None
    try:
        text = mem[addr:end].decode('ascii')
    except UnicodeDecodeError:
        return None
    if not text or any(ord(ch) < 32 or ord(ch) > 126 for ch in text):
        return None
    return text


def valid_rom_name(name: str) -> bool:
    if not name or len(name) > 64 or any(ch in name for ch in ' /\\'):
        return False
    return '.' in name or name.endswith('sma') or name.endswith('.key')


def roms_at(mem, addr, count):
    roms = []
    for n in range(count):
        off = addr + n * 20
        if off + 20 > len(mem):
            return None
        ptr, size, crc, typ, _extra = struct.unpack_from('<IIIII', mem, off)
        name = cstr(mem, ptr, 64)
        if not name or not valid_rom_name(name):
            return None
        if not (1 <= size <= 64 * 1024 * 1024) or typ > 16:
            return None
        roms.append((name, size, f'{crc:08x}'))
    return roms


def drivers_from(mem):
    found = {}
    for off in range(0, len(mem) - 24, 4):
        name_ptr = struct.unpack_from('<I', mem, off)[0]
        name = cstr(mem, name_ptr, 20)
        if not name or not (1 <= len(name) <= 16):
            continue
        if not all(ch.islower() or ch.isdigit() or ch == '_' for ch in name):
            continue
        for delta in (8, 12):
            romptr, count = struct.unpack_from('<II', mem, off + delta)
            if not (1 <= count <= 64):
                continue
            roms = roms_at(mem, romptr, count)
            if not roms:
                continue
            previous = found.get(name)
            if previous is None or len(roms) > len(previous):
                found[name] = roms
            break
    return found


def emit(sets):
    lines = [
        '// Generated by scripts/extract-arcade-sets.py from public/emulator/tatoemu.wasm.',
        '// Names, sizes, and CRCs are the emulator catalog. Do not edit by hand.',
        '// Each entry is [filename, size, crc32].',
        'export const ARCADE_SETS: Record<string, ReadonlyArray<readonly [string, number, string]>> = {',
    ]
    for name in sorted(sets):
        lines.append(f'  {json_string(name)}: [')
        for rom_name, size, crc in sets[name]:
            lines.append(f'    [{json_string(rom_name)}, {size}, {json_string(crc)}],')
        lines.append('  ],')
    lines.append('};')
    lines.append('')
    OUT.write_text('\n'.join(lines))


def json_string(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    mem = load_memory(WASM.read_bytes())
    sets = drivers_from(mem)
    if 'kof98' not in sets or 'doubledr' not in sets or 'dino' not in sets:
        raise SystemExit(f'incomplete extract: {len(sets)} drivers')
    kof98 = {name: crc for name, _size, crc in sets['kof98']}
    if kof98.get('242-p1.p1') != '8893df89' or kof98.get('242-p2.sp2') != '980aba4c' or kof98.get('242-m1.m1') != '4ef7016b':
        raise SystemExit('kof98 catalog check failed')
    emit(sets)
    print(f'{len(sets)} drivers -> {OUT} ({OUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
