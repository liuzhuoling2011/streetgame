#!/usr/bin/env node
/**
 * Split public/roms zips that are too big for GitHub.
 *
 * GitHub warns above 50 MB and rejects a file at 100 MB. Each zip larger than
 * 10 MiB becomes 10 MiB parts plus a manifest entry. Smaller zips stay whole.
 * Neo Geo BIOS (neogeo.zip) is never split and is always gitignored.
 *
 *   npm run roms:split
 *   node scripts/split-roms.mjs [rom-dir]
 */
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, open, readdir, readFile, rm, rmdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

const CHUNK_BYTES = 10 * 1024 * 1024;
const THRESHOLD_BYTES = CHUNK_BYTES;
const MAX_PARTS = 1000;

const romDir = path.resolve(process.argv[2] || 'public/roms');
const partsDir = path.join(romDir, 'parts');
const manifestPath = path.join(romDir, 'manifest.json');
const ignorePath = path.join(romDir, '.gitignore');

function isBios(name) {
  return name.toLowerCase() === 'neogeo.zip';
}

function formatMiB(bytes) {
  const mib = bytes / (1024 * 1024);
  return `${mib >= 10 ? mib.toFixed(1) : mib.toFixed(2)} MiB`;
}

function canonicalParts(name, size) {
  const count = Math.ceil(size / CHUNK_BYTES);
  const parts = [];
  for (let index = 0; index < count; index += 1) {
    parts.push(`parts/${name}.${String(index).padStart(3, '0')}`);
  }
  return parts;
}

async function hashStream(file) {
  const hash = createHash('sha256');
  const handle = await open(file, 'r');
  const buffer = Buffer.allocUnsafe(1024 * 1024);
  try {
    let position = 0;
    while (true) {
      const { bytesRead } = await handle.read(buffer, 0, buffer.length, position);
      if (bytesRead === 0) break;
      hash.update(buffer.subarray(0, bytesRead));
      position += bytesRead;
    }
  } finally {
    await handle.close();
  }
  return hash.digest('hex');
}

async function hashEach(parts) {
  const digests = [];
  for (const relative of parts) digests.push(await hashStream(path.join(romDir, relative)));
  return digests;
}

async function hashParts(parts) {
  const hash = createHash('sha256');
  const buffer = Buffer.allocUnsafe(1024 * 1024);
  for (const relative of parts) {
    const handle = await open(path.join(romDir, relative), 'r');
    try {
      let position = 0;
      while (true) {
        const { bytesRead } = await handle.read(buffer, 0, buffer.length, position);
        if (bytesRead === 0) break;
        hash.update(buffer.subarray(0, bytesRead));
        position += bytesRead;
      }
    } finally {
      await handle.close();
    }
  }
  return hash.digest('hex');
}

async function partsMatch(parts, size) {
  let offset = 0;
  for (let index = 0; index < parts.length; index += 1) {
    const relative = parts[index];
    if (relative.includes('..') || path.isAbsolute(relative)) return false;
    const full = path.resolve(romDir, relative);
    if (full !== path.join(partsDir, path.basename(relative))) return false;
    const info = await stat(full).catch(() => null);
    const expected = Math.min(CHUNK_BYTES, size - offset);
    if (!info?.isFile() || info.size !== expected || expected <= 0) return false;
    offset += expected;
  }
  return offset === size;
}

async function writeParts(file, name, size) {
  if (Math.ceil(size / CHUNK_BYTES) > MAX_PARTS) {
    throw new Error(`${name} would need more than ${MAX_PARTS} parts`);
  }
  await mkdir(partsDir, { recursive: true });
  const handle = await open(file, 'r');
  const parts = canonicalParts(name, size);
  try {
    let offset = 0;
    for (const relative of parts) {
      const length = Math.min(CHUNK_BYTES, size - offset);
      const buffer = Buffer.allocUnsafe(length);
      let filled = 0;
      while (filled < length) {
        const { bytesRead } = await handle.read(buffer, filled, length - filled, offset + filled);
        if (bytesRead === 0) throw new Error(`${name} ended early while writing ${relative}`);
        filled += bytesRead;
      }
      await writeFile(path.join(romDir, relative), buffer);
      offset += length;
    }
  } finally {
    await handle.close();
  }
  return parts;
}

async function readManifest() {
  try {
    const parsed = JSON.parse(await readFile(manifestPath, 'utf8'));
    if (!parsed || typeof parsed !== 'object' || !parsed.files || typeof parsed.files !== 'object') {
      return {};
    }
    return parsed.files;
  } catch (error) {
    if (error && error.code === 'ENOENT') return {};
    throw error;
  }
}

function renderIgnore(names) {
  const lines = [
    '# Generated by `npm run roms:split`. Do not edit.',
    '# Zips listed here are larger than 10 MiB. They stay on disk and are not committed.',
    '# Commit parts/, manifest.json, this file, and any zip that is not listed.',
    '# Neo Geo BIOS is never committed (the zip or any parts/).',
    'neogeo.zip',
    'parts/neogeo.zip.*',
  ];
  for (const name of names) {
    if (isBios(name)) continue;
    lines.push(name);
  }
  lines.push('');
  return lines.join('\n');
}

async function writeIfChanged(file, contents) {
  const current = await readFile(file, 'utf8').catch((error) => {
    if (error && error.code === 'ENOENT') return null;
    throw error;
  });
  if (current === contents) return false;
  await writeFile(file, contents);
  return true;
}

async function listZipNames() {
  const entries = await readdir(romDir, { withFileTypes: true });
  const names = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith('.zip')) continue;
    names.push(entry.name);
  }
  names.sort((a, b) => a.localeCompare(b));
  return names;
}

async function gitTracks(file) {
  try {
    await execFileAsync('git', ['ls-files', '--error-unmatch', '--', file], { cwd: romDir });
    return true;
  } catch {
    return false;
  }
}

async function removeOrphans(keep) {
  const info = await stat(partsDir).catch(() => null);
  if (!info?.isDirectory()) return [];
  const removed = [];
  for (const name of await readdir(partsDir)) {
    if (keep.has(name)) continue;
    await rm(path.join(partsDir, name), { recursive: true, force: true });
    removed.push(name);
  }
  const left = await readdir(partsDir);
  if (left.length === 0) await rmdirIfEmpty(partsDir);
  return removed.sort();
}

async function rmdirIfEmpty(dir) {
  const left = await readdir(dir).catch(() => null);
  if (left && left.length === 0) await rmdir(dir);
}

async function main() {
  const dirInfo = await stat(romDir).catch((error) => {
    if (error && error.code === 'ENOENT') {
      console.error(`No ROM directory at ${romDir}`);
      process.exitCode = 1;
      return null;
    }
    throw error;
  });
  if (!dirInfo) return;
  if (!dirInfo.isDirectory()) {
    console.error(`${romDir} is not a directory`);
    process.exitCode = 1;
    return;
  }

  const previous = await readManifest();
  const files = {};
  const ignored = [];
  const summary = [];
  let splitCount = 0;
  let unchangedCount = 0;
  let smallCount = 0;
  let biosCount = 0;

  for (const name of await listZipNames()) {
    const full = path.join(romDir, name);
    const info = await stat(full);
    if (isBios(name)) {
      biosCount += 1;
      summary.push(`skip    ${name}  ${formatMiB(info.size)}  BIOS is never committed`);
      continue;
    }
    if (info.size <= THRESHOLD_BYTES) {
      smallCount += 1;
      summary.push(`keep    ${name}  ${formatMiB(info.size)}`);
      continue;
    }

    const sha256 = await hashStream(full);
    const parts = canonicalParts(name, info.size);
    const prior = previous[name];
    const sameManifest = prior
      && prior.size === info.size
      && prior.sha256 === sha256
      && Array.isArray(prior.parts)
      && prior.parts.length === parts.length
      && prior.parts.every((part, index) => part === parts[index]);
    const intact = sameManifest && await partsMatch(parts, info.size) && await hashParts(parts) === sha256;
    if (!intact) {
      await writeParts(full, name, info.size);
      splitCount += 1;
      summary.push(`split   ${name}  ${formatMiB(info.size)}  ${parts.length} parts  sha256 ${sha256}`);
    } else {
      unchangedCount += 1;
      summary.push(`ready   ${name}  ${formatMiB(info.size)}  ${parts.length} parts  unchanged`);
    }
    files[name] = { size: info.size, sha256, parts, partSha256: await hashEach(parts) };
    ignored.push(name);
  }

  for (const [name, prior] of Object.entries(previous)) {
    if (files[name] || isBios(name)) continue;
    if (!prior || typeof prior.size !== 'number' || typeof prior.sha256 !== 'string' || !Array.isArray(prior.parts)) continue;
    const full = path.join(romDir, name);
    if (await stat(full).then((info) => info.isFile()).catch(() => false)) continue;
    const intact = await partsMatch(prior.parts, prior.size) && await hashParts(prior.parts) === prior.sha256;
    if (!intact) {
      summary.push(`drop    ${name}  source zip is gone and parts do not match`);
      continue;
    }
    files[name] = {
      size: prior.size,
      sha256: prior.sha256,
      parts: prior.parts,
      partSha256: await hashEach(prior.parts),
    };
    ignored.push(name);
    unchangedCount += 1;
    summary.push(`keep    ${name}  ${formatMiB(prior.size)}  ${prior.parts.length} parts  zip not on disk`);
  }

  const keepNames = new Set(Object.values(files).flatMap((entry) => entry.parts.map((part) => path.basename(part))));
  const removed = await removeOrphans(keepNames);

  const ordered = {};
  for (const name of Object.keys(files).sort((a, b) => a.localeCompare(b))) ordered[name] = files[name];
  const manifest = {
    version: 1,
    chunkBytes: CHUNK_BYTES,
    files: ordered,
  };
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  const manifestChanged = await writeIfChanged(manifestPath, manifestText);
  const ignoreChanged = await writeIfChanged(ignorePath, renderIgnore(ignored.sort((a, b) => a.localeCompare(b))));

  console.log(`ROM split  threshold ${formatMiB(THRESHOLD_BYTES)}  chunk ${formatMiB(CHUNK_BYTES)}`);
  console.log(`directory  ${romDir}`);
  for (const line of summary) console.log(line);
  if (removed.length > 0) console.log(`removed stale parts: ${removed.join(', ')}`);
  console.log(`manifest   ${manifestPath}${manifestChanged ? '' : ' (unchanged)'}`);
  console.log(`gitignore  ${ignorePath}${ignoreChanged ? '' : ' (unchanged)'}`);
  console.log(`summary    split ${splitCount}, unchanged ${unchangedCount}, kept small ${smallCount}, skipped BIOS ${biosCount}, stale parts ${removed.length}`);

  const tracked = [];
  for (const name of ignored) {
    if (await gitTracks(path.join(romDir, name))) tracked.push(name);
  }
  if (biosCount > 0) {
    for (const name of await listZipNames()) {
      if (isBios(name) && await gitTracks(path.join(romDir, name))) tracked.push(name);
    }
  }
  if (tracked.length > 0) {
    console.log('These files are already tracked. Stop tracking them before you commit:');
    for (const name of tracked) console.log(`  git rm --cached -- ${path.relative(process.cwd(), path.join(romDir, name))}`);
  }
}

await main();
